import os
import streamlit as st
from agent_workflow import app as agent_app

st.set_page_config(page_title="Data Copilot", page_icon="📊", layout="wide")
st.title("📊 Data Copilot")

# Manage chat history
if "messages" not in st.session_state:
    st.session_state.messages = []

# Display previous conversation messages
for msg in st.session_state.messages:
    with st.chat_message(msg["role"]):
        st.markdown(msg["content"])
        if "image" in msg and os.path.exists(msg["image"]):
            st.image(msg["image"])

# Get user input
if user_input := st.chat_input("Enter a prompt (e.g., Create a bar chart of sales)..."):
    st.session_state.messages.append({"role": "user", "content": user_input})
    with st.chat_message("user"):
        st.markdown(user_input)

    with st.chat_message("assistant"):
        with st.spinner("Agent is generating code and executing in Docker..."):
            initial_state = {
                "user_query": user_input,
                "code": "",
                "output": "",
                "error": "",
                "attempts": 0
            }

            final_state = agent_app.invoke(initial_state)
            
            output_text = final_state.get("output", "") or final_state.get("error", "No output received.")
            
            st.markdown(output_text)
            
            msg_data = {
                "role": "assistant",
                "content": output_text
            }
            
            # Display generated chart dynamically from final_state
            generated_files = final_state.get("generated_files", [])
            if generated_files:
                img_path = generated_files[0]
                if os.path.exists(img_path):
                    st.image(img_path, caption="Chart generated by Agent")
                    msg_data["image"] = img_path
                
            st.session_state.messages.append(msg_data)